    if (d > 1e-4) { if (d < r) { o.x = nx + dx / d * r; o.z = nz + dz / d * r; } return; }
    const a = o.x - q.x0, b = q.x1 - o.x, c = o.z - q.z0, e = q.z1 - o.z, m = Math.min(a, b, c, e);
