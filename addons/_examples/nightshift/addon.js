/* ---------- Конструктор поверху: стіни з отворами, меблі, точки — у локальних координатах від центру ---------- */
function mkFloor(k, def) {
  const cx = def.x, cz = def.z;
  const L = (x, z) => ({ x: cx + x, z: cz + z });
  const R = (x0, z0, x1, z1) => ({ x0: cx + Math.min(x0, x1), x1: cx + Math.max(x0, x1), z0: cz + Math.min(z0, z1), z1: cz + Math.max(z0, z1) });
  const f = { k, id: def.id, n: def.n, sh: def.sh, sub: def.sub, cx, cz, hx: def.hx, hz: def.hz, r: Math.ceil(Math.hypot(def.hx, def.hz)) + 2.5, pal: def.pal, WALLS: [], DOORS: [], FURN_L: [] };
  // стіна вздовж x (на висоті z) або вздовж z (на x); двері — центр або [центр, ширина, табличка]
  const wall = (horiz, at, a0, a1, doors = [], o = {}) => {
    const ds = doors.map(d => Array.isArray(d) ? { c: d[0], w: d[1] || 1.8, n: d[2] || '' } : { c: d, w: 1.8, n: '' }).sort((p, q) => p.c - q.c);
    let a = a0;
    for (const d of [...ds, { c: a1, w: 0 }]) {
      const g0 = d.c - d.w / 2; if (g0 > a + .01) f.WALLS.push(Object.assign(horiz ? R(a, at - .15, g0, at + .15) : R(at - .15, a, at + .15, g0), o));
      a = d.c + d.w / 2;
      if (d.w) f.DOORS.push({ x: cx + (horiz ? d.c : at), z: cz + (horiz ? at : d.c), h: horiz, w: d.w, n: d.n });
    }
  };
  const api = { L, R, P: (x, z, o) => Object.assign(L(x, z), o || {}), hw: (z, x0, x1, d, o) => wall(true, z, x0, x1, d, o), vw: (x, z0, z1, d, o) => wall(false, x, z0, z1, d, o),
    F: (t, x, z, rot = 0, len = 0, o = null) => f.FURN_L.push([t, x, z, rot, len, o]) };
  api.hw(-def.hz, -def.hx, def.hx, [], { out: 1 }); api.hw(def.hz, -def.hx, def.hx, [], { out: 1 }); api.vw(-def.hx, -def.hz, def.hz, [], { out: 1 }); api.vw(def.hx, -def.hz, def.hz, [], { out: 1 });
  def.plan(api, f);
  f.ROOMS = f.ROOMS.map(r => Object.assign({}, r));
  f.FURN = f.FURN_L.filter(e => !FURN_SOFT[e[0]]).map(([t, x, z, rot, len]) => {
    const d = FURN_T[t]; if (!d) return null;
    let w = len || d[0], dd = d[1]; if (Math.abs(Math.sin(rot)) > .5) [w, dd] = [dd, w];
    return R(x - w / 2, z - dd / 2, x + w / 2, z + dd / 2);
  }).filter(Boolean);
  f.BREAKERS = f.BRK_Z.map((z, i) => Object.assign({ x: f.PANEL_X + .55, z: cz + z }, { c: BRK_C[i][0], ic: BRK_C[i][1], n: BRK_C[i][2] }));
  f.MONITORS = f.MON_DESKS.map(([x, z, r]) => L(x, z - Math.cos(r) * .22));
  f.NC = f.hx * 4; f.NR = f.hz * 4; f.GX0 = cx - f.hx; f.GZ0 = cz - f.hz;
  f.roomAt = (x, z) => f.ROOMS.find(r => x - cx >= r.x0 && x - cx < r.x1 && z - cz >= r.z0 && z - cz < r.z1);
  return f;
}

